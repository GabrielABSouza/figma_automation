/**
 * Get an SVG string for a Lucide icon, with a specific color applied.
 * @param name - Lucide icon name (e.g., "home", "settings")
 * @param color - Hex color string (e.g., "#64748B")
 * @param size - Icon size in pixels (default 24)
 * @returns Complete SVG string ready for figma.createNodeFromSvg(), or null if icon not found
 */
export function getIconSvg(
  name: string,
  color: string,
  size: number = 24
): string | null {
  var svgStr = LUCIDE_ICONS[name];
  if (!svgStr) return null;

  // Replace currentColor with the actual color
  svgStr = svgStr.replace(/currentColor/g, color);

  // Replace size if not 24
  if (size !== 24) {
    svgStr = svgStr
      .replace(/width="24"/, 'width="' + size + '"')
      .replace(/height="24"/, 'height="' + size + '"');
  }

  return svgStr;
}
