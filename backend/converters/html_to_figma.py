"""Convert HTML with inline styles to a Figma node tree.

This module parses HTML generated by the LLM and converts it into a JSON
structure that maps 1:1 to Figma's Plugin API, so the plugin renderer
can apply properties directly without interpretation.
"""

from __future__ import annotations

import logging
import re
from html.parser import HTMLParser
from typing import Any

logger = logging.getLogger(__name__)

# ─── CSS Parsing Helpers ───


def _parse_inline_style(style_str: str) -> dict[str, str]:
    """Parse inline CSS like 'display: flex; color: #fff' into a dict."""
    props: dict[str, str] = {}
    if not style_str:
        return props
    for part in style_str.split(";"):
        part = part.strip()
        if ":" not in part:
            continue
        key, value = part.split(":", 1)
        props[key.strip().lower()] = value.strip()
    return props


def _parse_hex_color(hex_str: str) -> dict[str, float] | None:
    """Parse #RGB, #RRGGBB to {r, g, b} in 0-1 range."""
    h = hex_str.strip().lstrip("#")
    if len(h) == 3:
        h = h[0] * 2 + h[1] * 2 + h[2] * 2
    if len(h) != 6:
        return None
    try:
        return {
            "r": int(h[0:2], 16) / 255,
            "g": int(h[2:4], 16) / 255,
            "b": int(h[4:6], 16) / 255,
        }
    except ValueError:
        return None


def _parse_color(color_str: str) -> dict[str, float] | None:
    """Parse CSS color value to {r, g, b} (0-1 range)."""
    color_str = color_str.strip()
    if color_str.startswith("#"):
        return _parse_hex_color(color_str)

    # rgb(R, G, B) or rgba(R, G, B, A)
    m = re.match(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)", color_str)
    if m:
        return {
            "r": int(m.group(1)) / 255,
            "g": int(m.group(2)) / 255,
            "b": int(m.group(3)) / 255,
        }

    # Named colors (common subset)
    named = {
        "white": {"r": 1.0, "g": 1.0, "b": 1.0},
        "black": {"r": 0.0, "g": 0.0, "b": 0.0},
        "transparent": None,
        "red": {"r": 1.0, "g": 0.0, "b": 0.0},
        "green": {"r": 0.0, "g": 0.5, "b": 0.0},
        "blue": {"r": 0.0, "g": 0.0, "b": 1.0},
    }
    return named.get(color_str.lower())


def _parse_color_with_opacity(color_str: str) -> tuple[dict[str, float] | None, float]:
    """Parse color + extract opacity from rgba()."""
    color_str = color_str.strip()
    m = re.match(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)", color_str)
    if m:
        color = {
            "r": int(m.group(1)) / 255,
            "g": int(m.group(2)) / 255,
            "b": int(m.group(3)) / 255,
        }
        return color, float(m.group(4))
    return _parse_color(color_str), 1.0


def _parse_px(value: str) -> float | None:
    """Parse '16px' or '16' to float. Ignores em/rem/% units."""
    value = value.strip().lower()
    if value.endswith("%") or value.endswith("em") or value.endswith("rem"):
        return None
    value = value.replace("px", "")
    try:
        return float(value)
    except ValueError:
        return None


def _parse_letter_spacing(value: str, font_size: float) -> float | None:
    """Parse letter-spacing, supporting px and em units."""
    value = value.strip().lower()
    if value.endswith("em"):
        try:
            return float(value.replace("em", "")) * font_size
        except ValueError:
            return None
    return _parse_px(value)


def _parse_padding(value: str) -> tuple[float, float, float, float]:
    """Parse CSS padding shorthand to (top, right, bottom, left)."""
    parts = value.strip().split()
    nums = []
    for p in parts:
        n = _parse_px(p)
        nums.append(n if n is not None else 0)

    if len(nums) == 1:
        return (nums[0], nums[0], nums[0], nums[0])
    if len(nums) == 2:
        return (nums[0], nums[1], nums[0], nums[1])
    if len(nums) == 3:
        return (nums[0], nums[1], nums[2], nums[1])
    if len(nums) >= 4:
        return (nums[0], nums[1], nums[2], nums[3])
    return (0, 0, 0, 0)


def _parse_border(value: str) -> tuple[float, dict[str, float] | None]:
    """Parse 'Npx solid #color' to (weight, color)."""
    parts = value.strip().split()
    weight = 1.0
    color = None
    for part in parts:
        px = _parse_px(part)
        if px is not None:
            weight = px
        elif part.startswith("#") or part.startswith("rgb"):
            color = _parse_color(part)
        elif part in ("solid", "dashed", "dotted", "none") and part == "none":
            return (0, None)
    return (weight, color)


def _parse_box_shadow(value: str) -> dict[str, Any] | None:
    """Parse CSS box-shadow to Figma DROP_SHADOW effect."""
    # Match: offsetX offsetY blur [spread] color
    m = re.match(
        r"([\d.-]+)(?:px)?\s+([\d.-]+)(?:px)?\s+([\d.-]+)(?:px)?\s*(?:([\d.-]+)(?:px)?\s+)?"
        r"(rgba?\([^)]+\)|#[0-9a-fA-F]{3,8})",
        value.strip(),
    )
    if not m:
        return None

    offset_x = float(m.group(1))
    offset_y = float(m.group(2))
    blur = float(m.group(3))
    color_str = m.group(5)

    color_rgb, alpha = _parse_color_with_opacity(color_str)
    if not color_rgb:
        return None

    return {
        "type": "DROP_SHADOW",
        "color": {"r": color_rgb["r"], "g": color_rgb["g"], "b": color_rgb["b"], "a": alpha},
        "offset": {"x": offset_x, "y": offset_y},
        "radius": blur,
        "spread": 0,
        "visible": True,
        "blendMode": "NORMAL",
    }


def _parse_border_radius(value: str) -> float:
    """Parse border-radius value. Handles '12px', '50%', '9999px'."""
    value = value.strip()
    if value.endswith("%"):
        # 50% typically means circle — use a large number
        try:
            pct = float(value.replace("%", ""))
            return 9999 if pct >= 50 else pct
        except ValueError:
            return 0
    px = _parse_px(value)
    return px if px is not None else 0


def _font_weight_to_style(weight: int) -> str:
    """Convert CSS font-weight number to Figma font style name."""
    if weight >= 700:
        return "Bold"
    if weight >= 600:
        return "Semi Bold"
    if weight >= 500:
        return "Medium"
    return "Regular"


